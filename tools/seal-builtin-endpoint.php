<?php
if (PHP_SAPI !== 'cli') { http_response_code(403); exit('CLI only'); }
require_once dirname(__DIR__) . '/class/BuiltinEndpoint.php';

if ($argc > 1) {
    fwrite(STDERR, "Usage: php tools/seal-builtin-endpoint.php < endpoint.txt\nReads the HTTPS endpoint from stdin; writes only encrypted configuration.\n");
    exit($argc === 2 && $argv[1] === '--help' ? 0 : 1);
}

$temporary = null;
$status = 0;
try {
    $input = stream_get_contents(STDIN, 12003);
    if ($input === false || strlen($input) >= 12003) throw new RuntimeException('Endpoint input is too long or unreadable.');
    $endpoint = rtrim($input, "\r\n");
    unset($input);
    if (strlen($endpoint) > 12000 || !BuiltinEndpoint::validTemplate($endpoint)) {
        throw new RuntimeException('Expected an HTTPS query prefix ending in =, or a query {url} template, on port 443.');
    }
    if (!function_exists('openssl_encrypt')) throw new RuntimeException('OpenSSL is required.');
    $key = random_bytes(32);
    $share = random_bytes(32);
    $nonce = random_bytes(12);
    $tag = '';
    $ciphertext = openssl_encrypt($endpoint, 'aes-256-gcm', $key, OPENSSL_RAW_DATA, $nonce, $tag, BuiltinEndpoint::CONTEXT, 16);
    if ($ciphertext === false || strlen($tag) !== 16) throw new RuntimeException('Encryption failed.');
    $data = ['version' => 1, 'nonce' => base64_encode($nonce), 'tag' => base64_encode($tag),
        'keyShareA' => base64_encode($share), 'keyShareB' => base64_encode($key ^ $share), 'ciphertext' => base64_encode($ciphertext)];
    unset($key, $share, $endpoint);
    $contents = "<?php\n// Generated by tools/seal-builtin-endpoint.php. Ship this encrypted configuration.\nreturn " . var_export($data, true) . ";\n";
    $file = dirname(__DIR__) . '/includes/Builtin.Endpoint.php';
    // Stage next to the destination so a failed write keeps the previous release usable.
    $temporary = tempnam(dirname($file), '.builtin-');
    if ($temporary === false || file_put_contents($temporary, $contents, LOCK_EX) !== strlen($contents)) {
        throw new RuntimeException('Cannot write encrypted configuration.');
    }
    // This is distributable encrypted data; PHP-FPM may run as a different user.
    if (!chmod($temporary, 0644)) throw new RuntimeException('Cannot set configuration permissions.');
    if (!rename($temporary, $file)) throw new RuntimeException('Cannot replace encrypted configuration.');
    $temporary = null;
    fwrite(STDOUT, "Encrypted built-in endpoint updated. No endpoint or key was printed.\n");
} catch (Throwable $error) {
    fwrite(STDERR, 'Seal failed: ' . $error->getMessage() . "\n");
    $status = 1;
} finally {
    if (is_string($temporary) && is_file($temporary)) unlink($temporary);
}
exit($status);
